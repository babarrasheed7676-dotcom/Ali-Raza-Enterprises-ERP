-- Enforce posted-journal immutability at the database boundary.
CREATE OR REPLACE FUNCTION accounting.guard_journal_header_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'DRAFT' THEN
            RAISE EXCEPTION 'New journals must start in DRAFT status';
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'DELETE' THEN
        IF OLD.status <> 'DRAFT' THEN
            RAISE EXCEPTION 'Only DRAFT journals may be deleted';
        END IF;
        RETURN OLD;
    END IF;

    IF OLD.status = 'DRAFT'
       AND NEW.status = 'APPROVED'
       AND (to_jsonb(NEW) - ARRAY['status','approved_by','approved_at'])
           = (to_jsonb(OLD) - ARRAY['status','approved_by','approved_at']) THEN
        RETURN NEW;
    END IF;

    IF OLD.status = 'APPROVED'
       AND NEW.status = 'POSTED'
       AND (to_jsonb(NEW) - ARRAY['status','posted_by','posted_at'])
           = (to_jsonb(OLD) - ARRAY['status','posted_by','posted_at']) THEN
        RETURN NEW;
    END IF;

    IF OLD.status = 'POSTED'
       AND NEW.status = 'REVERSED'
       AND (to_jsonb(NEW) - 'status') = (to_jsonb(OLD) - 'status') THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'Journal header update is not an allowed workflow transition';
END;
$$;

CREATE TRIGGER trg_guard_journal_header_mutation
BEFORE INSERT OR UPDATE OR DELETE ON accounting.journal_entries
FOR EACH ROW EXECUTE FUNCTION accounting.guard_journal_header_mutation();

CREATE OR REPLACE FUNCTION accounting.guard_journal_line_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    parent_status VARCHAR(20);
    target_journal_id BIGINT;
    target_company_id BIGINT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        target_journal_id := NEW.journal_id;
        target_company_id := NEW.company_id;
    ELSE
        target_journal_id := OLD.journal_id;
        target_company_id := OLD.company_id;
    END IF;

    IF TG_OP = 'UPDATE'
       AND (NEW.journal_id <> OLD.journal_id OR NEW.company_id <> OLD.company_id) THEN
        RAISE EXCEPTION 'Journal lines cannot be moved between journals or companies';
    END IF;

    SELECT status INTO parent_status
    FROM accounting.journal_entries
    WHERE id = target_journal_id AND company_id = target_company_id
    FOR UPDATE;

    IF parent_status IS DISTINCT FROM 'DRAFT' THEN
        RAISE EXCEPTION 'Journal lines may only be changed while the journal is DRAFT';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_guard_journal_line_mutation
BEFORE INSERT OR UPDATE OR DELETE ON accounting.journal_lines
FOR EACH ROW EXECUTE FUNCTION accounting.guard_journal_line_mutation();

-- A posted journal must have at least two lines and its persisted line totals
-- must exactly match the balanced header. Deferred execution allows the
-- service to update the header and lines within one transaction.
CREATE OR REPLACE FUNCTION accounting.check_posted_journal_line_totals()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_id BIGINT;
    target_company_id BIGINT;
    header_status VARCHAR(20);
    header_debit NUMERIC(20,6);
    header_credit NUMERIC(20,6);
    line_count BIGINT;
    line_debit NUMERIC(20,6);
    line_credit NUMERIC(20,6);
BEGIN
    target_id := NEW.id;
    target_company_id := NEW.company_id;

    SELECT status, debit_total, credit_total
      INTO header_status, header_debit, header_credit
      FROM accounting.journal_entries
     WHERE id = target_id AND company_id = target_company_id;

    IF header_status IN ('POSTED', 'REVERSED') THEN
        SELECT COUNT(*), COALESCE(SUM(debit), 0), COALESCE(SUM(credit), 0)
          INTO line_count, line_debit, line_credit
          FROM accounting.journal_lines
         WHERE journal_id = target_id AND company_id = target_company_id;

        IF line_count < 2
           OR line_debit <= 0
           OR line_credit <= 0
           OR line_debit <> header_debit
           OR line_credit <> header_credit
           OR line_debit <> line_credit THEN
            RAISE EXCEPTION 'Posted journal must contain balanced lines matching header totals';
        END IF;
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_check_posted_journal_line_totals
AFTER INSERT OR UPDATE ON accounting.journal_entries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION accounting.check_posted_journal_line_totals();

