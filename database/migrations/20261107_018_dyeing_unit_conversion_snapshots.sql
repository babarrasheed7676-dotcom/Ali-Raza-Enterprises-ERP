-- Pin directional unit-conversion evidence per DRAFT Dyeing consumption line.
BEGIN;

CREATE TABLE production.dyeing_unit_conversion_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES core.company(id) ON DELETE RESTRICT,
    consumption_line_id BIGINT NOT NULL UNIQUE
        REFERENCES production.dyeing_consumption_lines(id) ON DELETE RESTRICT,
    status VARCHAR(30) NOT NULL,
    effective_on DATE NOT NULL,
    source_unit_id BIGINT NOT NULL REFERENCES master.units(id) ON DELETE RESTRICT,
    source_unit_code VARCHAR(30) NOT NULL,
    target_unit_id BIGINT NOT NULL REFERENCES master.units(id) ON DELETE RESTRICT,
    target_unit_code VARCHAR(30) NOT NULL,
    source_quantity NUMERIC(18,6) NOT NULL CHECK (source_quantity > 0),
    converted_quantity NUMERIC(18,6),
    conversion_factor NUMERIC(30,12),
    rounding_places SMALLINT,
    rounding_mode VARCHAR(30) NOT NULL DEFAULT 'ROUND_HALF_UP',
    configuration_version_id BIGINT
        REFERENCES configuration.config_versions(id) ON DELETE RESTRICT,
    snapshot JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_dyeing_unit_conversion_status CHECK (
        (status = 'NOT_REQUIRED'
         AND source_unit_code = target_unit_code
         AND source_unit_id = target_unit_id
         AND converted_quantity = source_quantity
         AND conversion_factor = 1
         AND configuration_version_id IS NULL
         AND rounding_places IS NULL)
        OR
        (status = 'APPROVED'
         AND source_unit_code <> target_unit_code
         AND source_unit_id <> target_unit_id
         AND converted_quantity > 0
         AND conversion_factor > 0
         AND configuration_version_id IS NOT NULL
         AND rounding_places BETWEEN 0 AND 6
         AND rounding_mode = 'ROUND_HALF_UP')
        OR
        (status = 'PENDING_CONFIGURATION'
         AND source_unit_code <> target_unit_code
         AND source_unit_id <> target_unit_id
         AND converted_quantity IS NULL
         AND configuration_version_id IS NULL
         AND conversion_factor IS NULL
         AND rounding_places IS NULL)
        OR
        (status = 'BLOCKED_PRECISION'
         AND source_unit_code <> target_unit_code
         AND source_unit_id <> target_unit_id
         AND converted_quantity IS NULL
         AND conversion_factor > 0
         AND configuration_version_id IS NOT NULL
         AND rounding_places BETWEEN 0 AND 6
         AND rounding_mode = 'ROUND_HALF_UP')
    )
);

CREATE INDEX ix_dyeing_unit_conversion_status
    ON production.dyeing_unit_conversion_snapshots(status, company_id);

CREATE OR REPLACE FUNCTION production.guard_dyeing_unit_conversion_snapshot()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    line_company BIGINT;
    line_date DATE;
    line_status VARCHAR(30);
    line_quantity NUMERIC(18,6);
    line_unit_id BIGINT;
    base_unit_id BIGINT;
    source_code VARCHAR(30);
    target_code VARCHAR(30);
    source_type VARCHAR(30);
    target_type VARCHAR(30);
    cfg configuration.config_versions%ROWTYPE;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Dyeing unit-conversion snapshots are immutable';
    END IF;

    SELECT o.company_id, o.dyeing_date, o.status, l.quantity, l.unit_id,
           i.base_unit_id, su.code, bu.code, su.unit_type, bu.unit_type
      INTO line_company, line_date, line_status, line_quantity, line_unit_id,
           base_unit_id, source_code, target_code, source_type, target_type
      FROM production.dyeing_consumption_lines l
      JOIN production.dyeing_orders o ON o.id = l.dyeing_order_id
      JOIN master.item_variants v ON v.id = l.item_variant_id
      JOIN master.items i ON i.id = v.item_id
      JOIN master.units su ON su.id = l.unit_id
      JOIN master.units bu ON bu.id = i.base_unit_id
     WHERE l.id = NEW.consumption_line_id
       AND su.is_active = TRUE AND bu.is_active = TRUE
     FOR SHARE OF l, o, su, bu;

    IF NOT FOUND OR line_status <> 'DRAFT'
       OR line_company <> NEW.company_id
       OR line_date <> NEW.effective_on
       OR line_quantity <> NEW.source_quantity
       OR line_unit_id <> NEW.source_unit_id
       OR base_unit_id <> NEW.target_unit_id
       OR source_code <> NEW.source_unit_code
       OR target_code <> NEW.target_unit_code
       OR source_type <> target_type THEN
        RAISE EXCEPTION 'Conversion snapshot must exactly match an active same-company DRAFT Dyeing line and its base unit';
    END IF;

    IF NEW.snapshot->>'status' IS DISTINCT FROM NEW.status
       OR NEW.snapshot->>'source_unit_code' IS DISTINCT FROM NEW.source_unit_code
       OR NEW.snapshot->>'target_unit_code' IS DISTINCT FROM NEW.target_unit_code
       OR (NEW.snapshot->>'source_quantity')::numeric IS DISTINCT FROM NEW.source_quantity THEN
        RAISE EXCEPTION 'Conversion snapshot JSON does not match its pinned columns';
    END IF;

    IF NEW.configuration_version_id IS NOT NULL THEN
        SELECT * INTO cfg
          FROM configuration.config_versions
         WHERE id = NEW.configuration_version_id
         FOR SHARE;
        IF NOT FOUND OR cfg.company_id <> NEW.company_id
           OR cfg.config_type <> 'UNIT_CONVERSION'
           OR cfg.status <> 'APPROVED'
           OR cfg.config_key <> upper(NEW.source_unit_code) || '-TO-' || upper(NEW.target_unit_code)
           OR cfg.effective_from > NEW.effective_on
           OR (cfg.effective_to IS NOT NULL AND cfg.effective_to < NEW.effective_on)
           OR cfg.payload->>'from_unit_code' <> NEW.source_unit_code
           OR cfg.payload->>'to_unit_code' <> NEW.target_unit_code
           OR (cfg.payload->>'factor')::numeric <> NEW.conversion_factor
           OR (cfg.payload->>'rounding_places')::integer <> NEW.rounding_places
           OR COALESCE((cfg.payload->>'active')::boolean, FALSE) IS NOT TRUE
           OR (NEW.snapshot->>'configuration_version_id')::bigint <> NEW.configuration_version_id THEN
            RAISE EXCEPTION 'Pinned unit-conversion version is not the exact approved effective rule';
        END IF;
    ELSIF NEW.status IN ('APPROVED', 'BLOCKED_PRECISION') THEN
        RAISE EXCEPTION 'Approved or precision-blocked conversion requires its exact configuration version';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_dyeing_unit_conversion_snapshot_immutable
BEFORE INSERT OR UPDATE OR DELETE
ON production.dyeing_unit_conversion_snapshots
FOR EACH ROW EXECUTE FUNCTION production.guard_dyeing_unit_conversion_snapshot();

CREATE OR REPLACE FUNCTION production.guard_dyeing_conversion_before_advance()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status = 'DRAFT' AND NEW.status <> 'DRAFT' AND EXISTS (
        SELECT 1
          FROM production.dyeing_consumption_lines l
          LEFT JOIN production.dyeing_unit_conversion_snapshots s
            ON s.consumption_line_id = l.id
         WHERE l.dyeing_order_id = NEW.id
           AND (s.id IS NULL OR s.status NOT IN ('NOT_REQUIRED', 'APPROVED'))
    ) THEN
        RAISE EXCEPTION 'Dyeing order cannot advance: every material line needs a valid unit-conversion snapshot; pending or precision-blocked conversions must be resolved';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_dyeing_conversion_before_advance
BEFORE UPDATE OF status ON production.dyeing_orders
FOR EACH ROW EXECUTE FUNCTION production.guard_dyeing_conversion_before_advance();

COMMIT;
