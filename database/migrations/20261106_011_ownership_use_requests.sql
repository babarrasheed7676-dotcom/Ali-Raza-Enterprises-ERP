-- Additive, auditable PARTY-use request/approval and locked-rate foundation.
BEGIN;
CREATE TABLE production.ownership_use_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES core.company(id) ON DELETE RESTRICT,
 use_module VARCHAR(20) NOT NULL CHECK (use_module IN ('DYEING','PACKING')),
 target_line_id BIGINT NOT NULL CHECK (target_line_id>0),
 ownership_policy_version_id BIGINT NOT NULL REFERENCES configuration.config_versions(id) ON DELETE RESTRICT,
 owner_party_id BIGINT NOT NULL REFERENCES master.parties(id) ON DELETE RESTRICT,
 requested_quantity NUMERIC(20,6) NOT NULL CHECK (requested_quantity>0),
 unit_id BIGINT REFERENCES master.units(id) ON DELETE RESTRICT,
 currency_code VARCHAR(3) NOT NULL DEFAULT 'PKR' CHECK (currency_code='PKR'),
 requested_unit_rate NUMERIC(20,6) NOT NULL CHECK (requested_unit_rate>0),
 locked_unit_rate NUMERIC(20,6),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 request_reason TEXT NOT NULL CHECK (length(btrim(request_reason)) BETWEEN 5 AND 1000),
 requested_by BIGINT NOT NULL REFERENCES core.users(id) ON DELETE RESTRICT,
 decided_by BIGINT REFERENCES core.users(id) ON DELETE RESTRICT,
 decided_at TIMESTAMPTZ, decision_note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_ownership_use_target UNIQUE(company_id,use_module,target_line_id),
 CONSTRAINT ck_ownership_use_decision CHECK (
  (status='PENDING' AND decided_by IS NULL AND decided_at IS NULL AND locked_unit_rate IS NULL)
  OR (status='APPROVED' AND decided_by IS NOT NULL AND decided_at IS NOT NULL
      AND decided_by<>requested_by AND locked_unit_rate=requested_unit_rate)
  OR (status='REJECTED' AND decided_by IS NOT NULL AND decided_at IS NOT NULL AND locked_unit_rate IS NULL)
 )
);
ALTER TABLE production.dyeing_consumption_lines ADD COLUMN ownership_use_request_id BIGINT;
ALTER TABLE production.packing_source_allocations ADD COLUMN ownership_use_request_id BIGINT;
ALTER TABLE production.dyeing_consumption_lines ADD CONSTRAINT fk_dyeing_ownership_use_request
 FOREIGN KEY(ownership_use_request_id) REFERENCES production.ownership_use_requests(id) ON DELETE RESTRICT;
ALTER TABLE production.packing_source_allocations ADD CONSTRAINT fk_packing_ownership_use_request
 FOREIGN KEY(ownership_use_request_id) REFERENCES production.ownership_use_requests(id) ON DELETE RESTRICT;
CREATE INDEX ix_ownership_use_pending ON production.ownership_use_requests(company_id,status,created_at) WHERE status='PENDING';

CREATE OR REPLACE FUNCTION production.guard_ownership_use_request()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
 policy_type VARCHAR(40); policy_key VARCHAR(100); policy_status VARCHAR(20);
 policy_payload JSONB; policy_company BIGINT; expected_key VARCHAR(100);
 target_status VARCHAR(30); target_company BIGINT; target_owner BIGINT;
 target_ownership BIGINT; target_qty NUMERIC; target_date DATE; policy_from DATE; policy_to DATE;
BEGIN
 IF TG_OP='UPDATE' AND OLD.status IN ('APPROVED','REJECTED') THEN
  RAISE EXCEPTION 'A decided PARTY-use request is immutable';
 END IF;
 expected_key := CASE WHEN NEW.use_module='DYEING' THEN 'DYEING-OWNERSHIP' ELSE 'NALKI-OWNERSHIP' END;
 SELECT config_type,config_key,status,payload,company_id,effective_from,effective_to
 INTO policy_type,policy_key,policy_status,policy_payload,policy_company,policy_from,policy_to
 FROM configuration.config_versions WHERE id=NEW.ownership_policy_version_id FOR SHARE;
 IF NOT FOUND OR policy_type<>'OWNERSHIP_POLICY' OR policy_key<>expected_key
 OR policy_status<>'APPROVED' OR policy_company<>NEW.company_id
 OR NOT COALESCE(policy_payload->'allowed_owners' ? 'PARTY',FALSE)
 OR COALESCE((policy_payload->>'party_rate_required')::boolean,FALSE) IS NOT TRUE
 OR COALESCE((policy_payload->>'party_stock_requires_approval')::boolean,FALSE) IS NOT TRUE THEN
  RAISE EXCEPTION 'An approved PARTY-enabled ownership policy is required';
 END IF;
 IF NEW.use_module='DYEING' THEN
  SELECT o.status,o.company_id,l.owner_party_id,l.ownership_type_id,l.quantity,o.dyeing_date
  INTO target_status,target_company,target_owner,target_ownership,target_qty,target_date
  FROM production.dyeing_consumption_lines l JOIN production.dyeing_orders o ON o.id=l.dyeing_order_id
  WHERE l.id=NEW.target_line_id FOR UPDATE OF l,o;
 ELSE
  SELECT o.status,o.company_id,a.owner_party_id,a.ownership_type_id,a.quantity_pieces,o.packing_date
  INTO target_status,target_company,target_owner,target_ownership,target_qty,target_date
  FROM production.packing_source_allocations a JOIN production.packing_orders o ON o.id=a.packing_order_id
  WHERE a.id=NEW.target_line_id FOR UPDATE OF a,o;
 END IF;
 IF NOT FOUND OR target_status<>'DRAFT' OR target_company<>NEW.company_id
 OR target_ownership<>2 OR target_owner<>NEW.owner_party_id OR target_qty<>NEW.requested_quantity THEN
  RAISE EXCEPTION 'Request must exactly match a same-company DRAFT PARTY line and quantity';
 END IF;
 IF target_date IS NULL OR target_date<policy_from OR target_date>COALESCE(policy_to,'infinity'::date) THEN
  RAISE EXCEPTION 'Ownership policy is not effective on the source document date';
 END IF;
 IF NEW.status='APPROVED' AND (NEW.decided_by IS NULL OR NEW.decided_by=NEW.requested_by
 OR NEW.locked_unit_rate IS DISTINCT FROM NEW.requested_unit_rate) THEN
  RAISE EXCEPTION 'Approval requires a different approver and exact locked rate';
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER trg_guard_ownership_use_request BEFORE INSERT OR UPDATE
ON production.ownership_use_requests FOR EACH ROW EXECUTE FUNCTION production.guard_ownership_use_request();

CREATE OR REPLACE FUNCTION production.guard_ownership_use_request_link()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE req production.ownership_use_requests%ROWTYPE;
BEGIN
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 IF TG_TABLE_NAME='dyeing_consumption_lines' THEN
  IF NEW.ownership_type_id=1 AND NEW.ownership_use_request_id IS NOT NULL THEN
   RAISE EXCEPTION 'OWN dyeing material cannot link a PARTY-use request';
  END IF;
  IF NEW.ownership_type_id=2 AND NEW.ownership_use_request_id IS NOT NULL THEN
   SELECT * INTO req FROM production.ownership_use_requests
   WHERE id=NEW.ownership_use_request_id AND use_module='DYEING'
   AND target_line_id=NEW.id AND owner_party_id=NEW.owner_party_id AND requested_quantity=NEW.quantity;
   IF NOT FOUND THEN RAISE EXCEPTION 'PARTY dyeing material requires its linked use request'; END IF;
  END IF;
 ELSE
  IF NEW.ownership_type_id=1 AND NEW.ownership_use_request_id IS NOT NULL THEN
   RAISE EXCEPTION 'OWN packing source cannot link a PARTY-use request';
  END IF;
  IF NEW.ownership_type_id=2 AND NEW.ownership_use_request_id IS NOT NULL THEN
   SELECT * INTO req FROM production.ownership_use_requests
   WHERE id=NEW.ownership_use_request_id AND use_module='PACKING'
   AND target_line_id=NEW.id AND owner_party_id=NEW.owner_party_id AND requested_quantity=NEW.quantity_pieces;
   IF NOT FOUND THEN RAISE EXCEPTION 'PARTY packing source requires its linked use request'; END IF;
  END IF;
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER trg_dyeing_ownership_use_request_link BEFORE INSERT OR UPDATE
ON production.dyeing_consumption_lines FOR EACH ROW EXECUTE FUNCTION production.guard_ownership_use_request_link();
CREATE TRIGGER trg_packing_ownership_use_request_link BEFORE INSERT OR UPDATE
ON production.packing_source_allocations FOR EACH ROW EXECUTE FUNCTION production.guard_ownership_use_request_link();
CREATE OR REPLACE FUNCTION production.assert_party_use_request_link()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE own_id BIGINT; req_id BIGINT; line_id BIGINT; party_id BIGINT; qty NUMERIC; module_code VARCHAR(20);
BEGIN
 IF TG_TABLE_NAME='dyeing_consumption_lines' THEN
  own_id:=NEW.ownership_type_id; req_id:=NEW.ownership_use_request_id; line_id:=NEW.id;
  party_id:=NEW.owner_party_id; qty:=NEW.quantity; module_code:='DYEING';
 ELSE
  own_id:=NEW.ownership_type_id; req_id:=NEW.ownership_use_request_id; line_id:=NEW.id;
  party_id:=NEW.owner_party_id; qty:=NEW.quantity_pieces; module_code:='PACKING';
 END IF;
 IF own_id=2 AND NOT EXISTS (
  SELECT 1 FROM production.ownership_use_requests r
  WHERE r.id=req_id AND r.use_module=module_code AND r.target_line_id=line_id
    AND r.owner_party_id=party_id AND r.requested_quantity=qty
 ) THEN
  RAISE EXCEPTION 'PARTY stock line must have a matching persisted ownership-use request before transaction commit';
 END IF;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER ct_dyeing_party_use_request_link
AFTER INSERT OR UPDATE ON production.dyeing_consumption_lines
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION production.assert_party_use_request_link();
CREATE CONSTRAINT TRIGGER ct_packing_party_use_request_link
AFTER INSERT OR UPDATE ON production.packing_source_allocations
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION production.assert_party_use_request_link();
COMMIT;
